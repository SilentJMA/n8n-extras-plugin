#!/usr/bin/env bash
# Developer tool: regenerate patches/ and overlay/ from a patched n8n checkout.
#
#   scripts/export-from-fork.sh <patched-n8n-dir> [base-ref]
#
# `base-ref` is the vanilla n8n commit or tag the checkout was patched from (default: the
# commit recorded in UPSTREAM). Edits to files that already exist in n8n become
# patches/core-seams.patch; files that are new become copies under overlay/.
#
# The module registration lines are not part of the patch: scripts/register-module.mjs
# writes them by anchor, which survives n8n changing the lines around them.
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
src="${1:?usage: export-from-fork.sh <patched-n8n-dir> [base-ref]}"
base="${2:-$(sed -n 's/^commit=//p' "$here/UPSTREAM")}"

cd "$src"
git rev-parse --verify "$base^{commit}" >/dev/null

rm -rf "$here/overlay" && mkdir -p "$here/overlay" "$here/patches"

# 1. Edits to existing files. The lockfile is regenerated by `pnpm install` on apply.
git diff --binary "$base" -- . \
	':!pnpm-lock.yaml' \
	':!packages/@n8n/backend-common/src/modules/modules.config.ts' \
	':!packages/@n8n/backend-common/src/modules/module-registry.ts' \
	':!packages/frontend/editor-ui/tsconfig.json' \
	':!packages/frontend/editor-ui/package.json' \
	':!packages/frontend/@n8n/frontend-vite-config/index.ts' \
	':!packages/frontend/editor-ui/src/app/modules.manifest.ts' \
	':!packages/cli/test/integration/shared/types.ts' \
	>"$here/patches/core-seams.patch"

# 2. New files (anything git would add that is not ignored).
git ls-files --others --exclude-standard -z | while IFS= read -r -d '' file; do
	mkdir -p "$here/overlay/$(dirname "$file")"
	cp -p "$file" "$here/overlay/$file"
done

echo "patch:   $(grep -c '^diff --git' "$here/patches/core-seams.patch") existing files edited"
echo "overlay: $(find "$here/overlay" -type f | wc -l | tr -d ' ') new files"
